"""Menú lateral que se esconde (31-oct-2026). Uso: /usr/bin/python3 probar_agenda_menu.py"""
from agenda_util import *
T = Prueba()
D = {'ag-duena': 'Sara'}
est = lambda pg: pg.evaluate("document.querySelector('.agenda-layout').dataset.menu")
anc = lambda pg, q: pg.evaluate("document.querySelector('%s').getBoundingClientRect().width" % q)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROMIUM)
    pg = abrir(contexto(b, 1280, 800, datos=D, config_abierta=False), '', 1800, config=False)
    T.v('computador: el menú sale abierto con nombres', est(pg) == 'abierto' and anc(pg, '.pestanas-agenda') > 200 and pg.is_visible('.pestana .p-largo >> nth=0'))
    T.v('hay botón «Ocultar menú»', 'Ocultar menú' in pg.inner_text('#menu-toggle') and not pg.is_visible('#menu-abrir'))
    ancho0 = anc(pg, '.hojas-contenido')
    pg.click('#menu-toggle'); pg.wait_for_timeout(300)
    T.v('al ocultar: el menú desaparece y el contenido se ensancha', est(pg) == 'oculto' and not pg.is_visible('.pestanas-agenda') and anc(pg, '.hojas-contenido') > ancho0 + 200, (ancho0, anc(pg, '.hojas-contenido')))
    T.v('queda el botón «Menú» para volver', pg.is_visible('#menu-abrir') and pg.get_attribute('#menu-abrir', 'aria-label') == 'Mostrar menú')
    T.v('sin desplazamiento horizontal', not pg.evaluate("document.documentElement.scrollWidth>innerWidth"))
    pg.reload(); pg.wait_for_timeout(1800)
    T.v('la elección se recuerda al recargar', est(pg) == 'oculto')
    pg.click('#menu-abrir'); pg.wait_for_timeout(300)
    T.v('al mostrar vuelve al menú abierto', est(pg) == 'abierto' and pg.is_visible('.pestanas-agenda'))
    T.v('los 7 botones de sección siguen siendo 7', pg.locator('.pestana').count() == 7)
    pg.click('.pestana >> nth=4'); pg.wait_for_timeout(400)
    T.v('el menú sigue funcionando (abre la vista de sección)', pg.evaluate("!document.getElementById('vista-seccion').hidden"))
    T.v('sin errores de JavaScript', not pg.errs, pg.errs)
    pg.close()
    # tableta
    ctx = contexto(b, 834, 1112, datos=D, config_abierta=False)
    pg = abrir(ctx, '', 1800, config=False)
    T.v('tableta: barra angosta con solo íconos', est(pg) == 'riel' and anc(pg, '.pestanas-agenda') < 90 and not pg.is_visible('.pestana .p-largo >> nth=0'), anc(pg, '.pestanas-agenda'))
    T.v('tableta: «Ampliar menú» tiene nombre accesible', pg.get_attribute('#menu-toggle', 'aria-label') == 'Ampliar menú')
    T.v('tableta: los botones tienen nombre accesible', all(pg.evaluate("[...document.querySelectorAll('.pestana')].every(b=>b.innerText.trim().length>0 || b.getAttribute('aria-label'))") for _ in [0]) )
    pg.click('#menu-toggle'); pg.wait_for_timeout(300)
    T.v('tableta: al ampliar se ven los nombres', est(pg) == 'abierto' and pg.is_visible('.pestana .p-largo >> nth=0') and anc(pg, '.pestanas-agenda') > 150)
    T.v('tableta: sin desplazamiento horizontal', not pg.evaluate("document.documentElement.scrollWidth>innerWidth"))
    pg.close()
    # celular: no cambia nada
    pg = abrir(contexto(b, 390, 844, datos=D, config_abierta=False), '', 1800, config=False)
    T.v('celular: sin botones del menú lateral y barra de abajo intacta', not pg.is_visible('#menu-toggle') and not pg.is_visible('#menu-abrir') and pg.evaluate("getComputedStyle(document.querySelector('.pestanas-agenda')).position") == 'fixed')
    T.v('celular: sin desplazamiento horizontal', not pg.evaluate("document.documentElement.scrollWidth>innerWidth"))
    pg.close()
    # inglés
    ctx = contexto(b, 1280, 800, datos=D, config_abierta=False); ctx.add_init_script("localStorage.setItem('lrAgendaIdioma','en')")
    pg = abrir(ctx, '', 2200, config=False)
    T.v('en inglés: «Hide menu»', 'Hide menu' in pg.inner_text('#menu-toggle'), pg.inner_text('#menu-toggle'))
    b.close()
T.fin()
